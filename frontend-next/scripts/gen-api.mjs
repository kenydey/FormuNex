// Regenerate src/api/openapi.json + src/api/schema.d.ts from the FastAPI app (方案 §3.1: types come from
// OpenAPI, never by hand). Needs the backend virtualenv: ../backend/.venv (or PYTHON=/path/to/python).
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import openapiTS, { astToString } from "openapi-typescript";

const python = process.env.PYTHON || "../backend/.venv/bin/python";
const json = execFileSync(python, ["-c", "import json; from app.main import app; print(json.dumps(app.openapi()))"], {
  cwd: "../backend",
  env: { ...process.env, FORMUNEX_DB_URL: process.env.FORMUNEX_DB_URL || "sqlite:///:memory:" },
  maxBuffer: 64 * 1024 * 1024,
}).toString();
const spec = JSON.parse(json);
writeFileSync("src/api/openapi.json", JSON.stringify(spec, null, 1) + "\n");
const ast = await openapiTS(spec);
writeFileSync("src/api/schema.d.ts", "/* Generated by scripts/gen-api.mjs — do not edit. */\n" + astToString(ast));
console.log(`openapi: ${Object.keys(spec.paths).length} paths`);
