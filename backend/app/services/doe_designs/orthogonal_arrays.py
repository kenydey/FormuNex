"""Taguchi orthogonal arrays and factor / interaction column assignment (方案 §5.3, M6).

Arrays are *constructed*, not typed in, so every one is checked by
:func:`is_orthogonal` in the tests:

* ``q``-level arrays over GF(q), q ∈ {2, 3, 4, 5}: ``L(q^m)`` with ``q^m`` runs and
  ``(q^m − 1)/(q − 1)`` columns, one per normalised non-zero vector of GF(q)^m
  (L4, L8, L16, L32, L64 / L9, L27, L81 / L16(4^5), L64(4^21) / L25(5^6)).
  The interaction of columns u and v lives in the q − 1 columns ``u + k·v``.
  Two-level arrays use Taguchi's column numbering (column 3 = 1×2, 5 = 1×4 …).
* L12 (2^11): Plackett–Burman; interactions are spread over all columns, so
  it is for main effects only.
* L18 (2^1 × 3^7): the standard mixed array (main effects; the 1×2 interaction
  is the only clean one).

Levels in the arrays are 0-based internally; designs report the factors' own
level values.
"""
from __future__ import annotations

import itertools
from dataclasses import dataclass, field
from typing import Any

# --------------------------------------------------------------------------- finite fields


def _gf(q: int) -> tuple[list[list[int]], list[list[int]]]:
    """Addition and multiplication tables of GF(q)."""
    if q in (2, 3, 5):
        return ([[(a + b) % q for b in range(q)] for a in range(q)],
                [[(a * b) % q for b in range(q)] for a in range(q)])
    if q == 4:  # GF(2)[x]/(x^2 + x + 1): 0, 1, x=2, x+1=3
        add = [[a ^ b for b in range(4)] for a in range(4)]
        mul = [[0, 0, 0, 0], [0, 1, 2, 3], [0, 2, 3, 1], [0, 3, 1, 2]]
        return add, mul
    raise ValueError(f"GF({q}) not supported")


def _normalised_vectors(q: int, m: int) -> list[tuple[int, ...]]:
    """Non-zero vectors of GF(q)^m whose first non-zero coordinate is 1."""
    out = []
    for v in itertools.product(range(q), repeat=m):
        nz = next((x for x in v if x), None)
        if nz == 1:
            out.append(v)
    return out


def _bit_reverse(j: int, m: int) -> int:
    return int(format(j, f"0{m}b")[::-1], 2)


@dataclass(frozen=True)
class OA:
    name: str
    runs: int
    levels: tuple[int, ...]  # level count per column
    rows: tuple[tuple[int, ...], ...]  # 0-based levels
    q: int | None = None  # field size for GF arrays (interactions available)
    m: int | None = None
    vectors: tuple[tuple[int, ...], ...] | None = None  # column generators (GF arrays)

    @property
    def columns(self) -> int:
        return len(self.levels)

    def column_of(self, vector: tuple[int, ...]) -> int:
        """0-based column index of a (not necessarily normalised) non-zero vector."""
        assert self.vectors is not None and self.q is not None
        add, mul = _gf(self.q)
        nz = next(x for x in vector if x)
        inv = next(b for b in range(1, self.q) if mul[nz][b] == 1)
        norm = tuple(mul[inv][x] for x in vector)
        return self.vectors.index(norm)

    def interaction_columns(self, a: int, b: int) -> list[int]:
        """Columns carrying the interaction of columns *a* and *b* (0-based)."""
        if self.vectors is None or self.q is None:
            raise ValueError(f"{self.name} has no clean interaction columns")
        add, mul = _gf(self.q)
        u, v = self.vectors[a], self.vectors[b]
        return sorted({self.column_of(tuple(add[x][mul[k][y]] for x, y in zip(u, v, strict=True)))
                       for k in range(1, self.q)})


def _gf_array(q: int, m: int) -> OA:
    add, mul = _gf(q)
    if q == 2:
        # Taguchi numbering: column j (1-based) is generated by bit-reverse(j); run bits MSB-first.
        vectors = [tuple(int(c) for c in format(_bit_reverse(j, m), f"0{m}b")) for j in range(1, 2 ** m)]
    else:
        basics = [tuple(1 if i == k else 0 for i in range(m)) for k in range(m)]
        rest = [v for v in _normalised_vectors(q, m) if v not in basics]
        vectors = basics + rest
    rows = []
    for run in itertools.product(range(q), repeat=m):
        row = []
        for v in vectors:
            s = 0
            for x, y in zip(run, v, strict=True):
                s = add[s][mul[x][y]]
            row.append(s)
        rows.append(tuple(row))
    name = f"L{q ** m}" + ("" if q in (2, 3) else f"({q}^{len(vectors)})")
    return OA(name, q ** m, tuple([q] * len(vectors)), tuple(rows), q, m, tuple(vectors))


def _l12() -> OA:
    gen = [1, 1, 0, 1, 1, 1, 0, 0, 0, 1, 0]  # Plackett–Burman generator (1 = level 2)
    rows = [tuple([0] * 11)]
    row = gen
    for _ in range(11):
        rows.append(tuple(row))
        row = [row[-1]] + row[:-1]
    return OA("L12", 12, tuple([2] * 11), tuple(rows))


_L18 = (
    "11111111", "11222222", "11333333", "12112233", "12223311", "12331122",
    "13121323", "13232131", "13313212", "21133221", "21211332", "21322113",
    "22123132", "22231213", "22312321", "23132312", "23213123", "23321231",
)


def _l18() -> OA:
    rows = tuple(tuple(int(c) - 1 for c in r) for r in _L18)
    return OA("L18", 18, (2,) + (3,) * 7, rows)


def catalogue() -> list[OA]:
    out = [_gf_array(2, m) for m in (2, 3, 4, 5, 6)]
    out += [_gf_array(3, m) for m in (2, 3, 4)]
    out += [_gf_array(4, 2), _gf_array(4, 3), _gf_array(5, 2), _l12(), _l18()]
    return sorted(out, key=lambda a: (a.runs, a.name))


def get_array(name: str) -> OA:
    for a in catalogue():
        if a.name == name:
            return a
    raise ValueError(f"未知正交表 {name}；可选：{', '.join(a.name for a in catalogue())}")


def is_orthogonal(oa: OA, columns: list[int] | None = None) -> bool:
    """Strength 2: every pair of columns shows each level combination equally often."""
    cols = range(oa.columns) if columns is None else columns
    for a, b in itertools.combinations(cols, 2):
        counts: dict[tuple[int, int], int] = {}
        for r in oa.rows:
            counts[(r[a], r[b])] = counts.get((r[a], r[b]), 0) + 1
        if len(counts) != oa.levels[a] * oa.levels[b] or len(set(counts.values())) != 1:
            return False
    return True


# --------------------------------------------------------------------------- assignment


class OrthogonalError(ValueError):
    pass


@dataclass
class OAFactor:
    name: str
    levels: list[Any]


@dataclass
class OADesign:
    array: str
    runs: list[dict[str, Any]]
    assignment: dict[str, int]  # factor → 1-based column
    interactions: dict[str, list[int]] = field(default_factory=dict)  # "A×B" → 1-based columns
    free_columns: list[int] = field(default_factory=list)  # 1-based, usable for error estimation
    dummy_levels: dict[str, list[Any]] = field(default_factory=dict)
    notes: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {"array": self.array, "runs": self.runs, "assignment": self.assignment,
                "interactions": self.interactions, "free_columns": self.free_columns,
                "dummy_levels": self.dummy_levels, "notes": self.notes}


def _place(oa: OA, factors: list[OAFactor], columns_for: list[list[int]],
           interactions: list[tuple[int, int]]) -> tuple[list[int], dict[tuple[int, int], list[int]]] | None:
    """Backtracking: a column per factor so that requested interaction columns collide with nothing."""

    def rec(i: int, chosen: tuple[int, ...], used: frozenset[int],
            inter: dict[tuple[int, int], list[int]]) -> tuple[list[int], dict] | None:
        if i == len(factors):
            return list(chosen), inter
        for col in columns_for[i]:
            if col in used:
                continue
            taken = set(used) | {col}
            new_inter = dict(inter)
            ok = True
            for a, b in interactions:
                if b != i:
                    continue
                cols = oa.interaction_columns(chosen[a], col)
                if taken & set(cols):
                    ok = False
                    break
                taken |= set(cols)
                new_inter[(a, b)] = cols
            if ok:
                found = rec(i + 1, chosen + (col,), frozenset(taken), new_inter)
                if found is not None:
                    return found
        return None

    return rec(0, (), frozenset(), {})


def _candidates(factors: list[OAFactor], interactions: list[tuple[int, int]]) -> list[OA]:
    counts = sorted({len(f.levels) for f in factors})
    arrays = catalogue()
    if len(counts) == 1:
        q = counts[0]
        if q not in (2, 3, 4, 5):
            raise OrthogonalError(f"不支持 {q} 水平因子（支持 2/3/4/5 水平）")
        same = [a for a in arrays if set(a.levels) == {q}]
        if interactions:
            same = [a for a in same if a.vectors is not None]
        return same
    if counts == [2, 3]:
        if interactions:
            raise OrthogonalError("混合水平设计（2 与 3 水平）不支持交互作用列，请改用 D-最优设计")
        return [a for a in arrays if a.name == "L18"] + [a for a in arrays if set(a.levels) == {3}]
    raise OrthogonalError(f"不支持的水平组合 {counts}：请统一水平数，或改用 D-最优设计")


def design(factors: list[OAFactor], *, interactions: list[tuple[str, str]] | None = None,
           array: str | None = None) -> OADesign:
    if not factors:
        raise OrthogonalError("至少需要一个因子")
    names = [f.name for f in factors]
    if len(set(names)) != len(names):
        raise OrthogonalError("因子名重复")
    idx = {n: i for i, n in enumerate(names)}
    pairs = []
    for a, b in interactions or []:
        if a not in idx or b not in idx or a == b:
            raise OrthogonalError(f"交互作用 {a}×{b} 引用了未知因子")
        pairs.append(tuple(sorted((idx[a], idx[b]))))
    pairs = sorted(set(pairs), key=lambda p: (p[1], p[0]))
    options = [get_array(array)] if array else _candidates(factors, pairs)
    notes: list[str] = []
    for oa in options:
        columns_for = []
        dummy: dict[str, list[Any]] = {}
        for f in factors:
            k = len(f.levels)
            exact = [c for c in range(oa.columns) if oa.levels[c] == k]
            wider = [c for c in range(oa.columns) if oa.levels[c] > k] if not pairs else []
            columns_for.append(exact + wider)
        if any(not c for c in columns_for):
            continue
        if pairs and oa.vectors is None:
            continue
        placed = _place(oa, factors, columns_for, pairs)
        if placed is None:
            continue
        chosen, inter = placed
        runs = []
        for r in oa.rows:
            run = {}
            for f, col in zip(factors, chosen, strict=True):
                lv = r[col]
                if lv >= len(f.levels):  # dummy level: reuse the first levels (Taguchi dummy treatment)
                    dummy.setdefault(f.name, list(f.levels[: oa.levels[col] - len(f.levels)]))
                    lv = lv - len(f.levels)
                run[f.name] = f.levels[lv]
            runs.append(run)
        used = set(chosen) | {c for cols in inter.values() for c in cols}
        if dummy:
            notes.append("拟水平：" + "；".join(f"{k} 在第 {chosen[idx[k]] + 1} 列重复使用水平 {v}" for k, v in dummy.items()))
        if oa.name == "L12":
            notes.append("L12 的交互作用分散在各列中，只用于主效应筛选")
        if oa.name == "L18":
            notes.append("L18 只估计主效应（第 1、2 列的交互作用除外）")
        return OADesign(
            array=oa.name, runs=runs, assignment={f.name: c + 1 for f, c in zip(factors, chosen, strict=True)},
            interactions={f"{names[a]}×{names[b]}": [c + 1 for c in cols] for (a, b), cols in inter.items()},
            free_columns=[c + 1 for c in range(oa.columns) if c not in used], dummy_levels=dummy, notes=notes)
    raise OrthogonalError("没有能容纳这些因子与交互作用的正交表（因子或交互作用过多），请减少交互作用或改用 D-最优设计")
