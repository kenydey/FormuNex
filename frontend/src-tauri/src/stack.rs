//! The local FormuNex stack (方案 §2.2 “桌面单机版” / §3.5): compose file and generated secrets in the
//! app data directory, start / stop, offline image import, administrator creation, pg_dump backups and
//! upgrades (always backed up first).

use rand::{distributions::Alphanumeric, Rng};
use serde::Serialize;
use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use crate::config::DesktopConfig;
use crate::docker::Docker;
use crate::error::{DesktopError, Result};

/// Shipped with the app; written to `<app_data>/compose.yml`.
pub const COMPOSE_TEMPLATE: &str = include_str!("../../../deploy/desktop/docker-compose.desktop.yml");
pub const COMPOSE_FILE: &str = "compose.yml";
pub const ENV_FILE: &str = ".env";
pub const BACKUP_DIR: &str = "backups";
pub const KEEP_BACKUPS: usize = 10;

/// Generated once, never rewritten: changing them would lock the stack out of its own volumes.
const SECRET_KEYS: [(&str, usize); 3] =
    [("FORMUNEX_PG_PASSWORD", 32), ("FORMUNEX_NEO4J_PASSWORD", 32), ("FORMUNEX_AUTH_JWT_SECRET", 64)];

/// Roles of the first administrator of a single-user desktop install (all built-in roles; four-level
/// sign-off still needs four different people, so a desktop install cannot release on its own).
pub const ADMIN_ROLES: &str = "sys_admin,project_lead,rd_engineer,ehs_regulatory,quality,release_manager";

pub fn random_secret(len: usize) -> String {
    rand::thread_rng().sample_iter(&Alphanumeric).take(len).map(char::from).collect()
}

pub fn parse_env(text: &str) -> BTreeMap<String, String> {
    text.lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .filter_map(|l| l.split_once('='))
        .map(|(k, v)| (k.trim().to_string(), v.trim().to_string()))
        .collect()
}

/// Paths of the stack files inside the app data directory.
#[derive(Clone, Debug)]
pub struct StackFiles {
    pub dir: PathBuf,
}

impl StackFiles {
    pub fn new(dir: impl Into<PathBuf>) -> Self {
        Self { dir: dir.into() }
    }
    pub fn compose(&self) -> PathBuf {
        self.dir.join(COMPOSE_FILE)
    }
    pub fn env(&self) -> PathBuf {
        self.dir.join(ENV_FILE)
    }
    pub fn backups(&self) -> PathBuf {
        self.dir.join(BACKUP_DIR)
    }

    /// Write the compose file and the `.env`: secrets generated on first use and kept afterwards; image,
    /// version and port follow the current config.
    pub fn prepare(&self, cfg: &DesktopConfig) -> Result<()> {
        fs::create_dir_all(&self.dir)?;
        let compose = self.compose();
        if fs::read_to_string(&compose).ok().as_deref() != Some(COMPOSE_TEMPLATE) {
            fs::write(&compose, COMPOSE_TEMPLATE)?;
        }
        let mut env = fs::read_to_string(self.env()).map(|t| parse_env(&t)).unwrap_or_default();
        for (key, len) in SECRET_KEYS {
            env.entry(key.to_string()).or_insert_with(|| random_secret(len));
        }
        env.insert("FORMUNEX_IMAGE".into(), cfg.image.clone());
        env.insert("FORMUNEX_VERSION".into(), cfg.version.clone());
        env.insert("FORMUNEX_API_PORT".into(), cfg.api_port.to_string());
        let mut text =
            String::from("# Generated by the FormuNex desktop app. Keep private: contains database passwords.\n");
        for (k, v) in &env {
            text.push_str(&format!("{k}={v}\n"));
        }
        write_private(&self.env(), &text)?;
        Ok(())
    }

    pub fn docker(&self, bin: PathBuf) -> Docker {
        Docker::new(bin, self.compose(), self.env())
    }

    /// Backups, newest first.
    pub fn list_backups(&self) -> Vec<BackupInfo> {
        let mut out: Vec<BackupInfo> = fs::read_dir(self.backups())
            .into_iter()
            .flatten()
            .flatten()
            .filter(|e| e.file_name().to_string_lossy().ends_with(".dump"))
            .filter_map(|e| {
                let meta = e.metadata().ok()?;
                Some(BackupInfo {
                    path: e.path().display().to_string(),
                    name: e.file_name().to_string_lossy().into_owned(),
                    bytes: meta.len(),
                })
            })
            .collect();
        out.sort_by(|a, b| b.name.cmp(&a.name));
        out
    }

    fn prune_backups(&self) -> Result<()> {
        for old in self.list_backups().into_iter().skip(KEEP_BACKUPS) {
            fs::remove_file(old.path)?;
        }
        Ok(())
    }
}

#[derive(Serialize, Clone, Debug, PartialEq, Eq)]
pub struct BackupInfo {
    pub path: String,
    pub name: String,
    pub bytes: u64,
}

fn write_private(path: &Path, text: &str) -> Result<()> {
    let tmp = path.with_extension("tmp");
    fs::write(&tmp, text)?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        fs::set_permissions(&tmp, fs::Permissions::from_mode(0o600))?;
    }
    fs::rename(&tmp, path)?;
    Ok(())
}

/// `pg_dump -Fc` of the stack database into `<app_data>/backups/formunex-<stamp>[-<label>].dump`; keeps
/// the newest [`KEEP_BACKUPS`].
pub fn backup(files: &StackFiles, docker: &Docker, label: &str) -> Result<BackupInfo> {
    fs::create_dir_all(files.backups())?;
    let stamp = chrono::Local::now().format("%Y%m%d-%H%M%S");
    let suffix: String = label.chars().filter(|c| c.is_ascii_alphanumeric() || *c == '-').collect();
    let name =
        if suffix.is_empty() { format!("formunex-{stamp}.dump") } else { format!("formunex-{stamp}-{suffix}.dump") };
    let out = docker.run(
        &docker.compose_args(&["exec", "-T", "postgres", "pg_dump", "-U", "formunex", "-d", "formunex", "-Fc"]),
        &[],
    )?;
    if out.stdout.is_empty() {
        return Err(DesktopError::Docker { command: "pg_dump".into(), message: "备份为空".into() });
    }
    let path = files.backups().join(&name);
    fs::write(&path, &out.stdout)?;
    files.prune_backups()?;
    Ok(BackupInfo { path: path.display().to_string(), name, bytes: out.stdout.len() as u64 })
}

/// Create the first administrator inside the api container. The password travels in the child process
/// environment (`-e NAME` without a value forwards it), never on a command line.
pub fn create_admin(docker: &Docker, username: &str, display_name: &str, password: &str) -> Result<()> {
    if username.is_empty() || !username.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | '-' | '.')) {
        return Err(DesktopError::Config("用户名只能包含字母、数字、_ - .".into()));
    }
    let args = docker.compose_args(&[
        "exec",
        "-T",
        "-e",
        "FORMUNEX_NEW_USER_PASSWORD",
        "api",
        "python",
        "scripts/create_user.py",
        username,
        "--roles",
        ADMIN_ROLES,
        "--display-name",
        display_name,
    ]);
    docker.run(&args, &[("FORMUNEX_NEW_USER_PASSWORD", password)])?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn template_is_the_desktop_compose_file() {
        assert!(COMPOSE_TEMPLATE.contains("name: formunex"));
        assert!(COMPOSE_TEMPLATE.contains("127.0.0.1:${FORMUNEX_API_PORT"));
        for (key, _) in SECRET_KEYS {
            assert!(COMPOSE_TEMPLATE.contains(key), "{key}");
        }
    }

    #[test]
    fn prepare_generates_secrets_once_and_follows_config() {
        let dir = tempfile::tempdir().unwrap();
        let files = StackFiles::new(dir.path());
        let mut cfg = DesktopConfig::default();
        files.prepare(&cfg).unwrap();
        let first = parse_env(&fs::read_to_string(files.env()).unwrap());
        assert_eq!(first["FORMUNEX_PG_PASSWORD"].len(), 32);
        assert_eq!(first["FORMUNEX_AUTH_JWT_SECRET"].len(), 64);
        assert_eq!(first["FORMUNEX_VERSION"], cfg.version);
        cfg.version = "9.9.9".into();
        cfg.api_port = 18000;
        files.prepare(&cfg).unwrap();
        let second = parse_env(&fs::read_to_string(files.env()).unwrap());
        assert_eq!(second["FORMUNEX_PG_PASSWORD"], first["FORMUNEX_PG_PASSWORD"]);
        assert_eq!(second["FORMUNEX_AUTH_JWT_SECRET"], first["FORMUNEX_AUTH_JWT_SECRET"]);
        assert_eq!(second["FORMUNEX_VERSION"], "9.9.9");
        assert_eq!(second["FORMUNEX_API_PORT"], "18000");
        assert_eq!(fs::read_to_string(files.compose()).unwrap(), COMPOSE_TEMPLATE);
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            assert_eq!(fs::metadata(files.env()).unwrap().permissions().mode() & 0o777, 0o600);
        }
    }

    #[test]
    fn parse_env_ignores_comments_and_blank_lines() {
        let env = parse_env("# x\n\nA=1\n B = two \nbad\n");
        assert_eq!(env.len(), 2);
        assert_eq!(env["B"], "two");
    }

    #[cfg(unix)]
    fn fake_docker(dir: &Path, script: &str) -> PathBuf {
        use std::os::unix::fs::PermissionsExt;
        let bin = dir.join("docker");
        fs::write(&bin, format!("#!/bin/sh\n{script}\n")).unwrap();
        fs::set_permissions(&bin, fs::Permissions::from_mode(0o755)).unwrap();
        bin
    }

    #[cfg(unix)]
    #[test]
    fn backup_writes_dump_and_keeps_the_newest() {
        let dir = tempfile::tempdir().unwrap();
        let files = StackFiles::new(dir.path());
        let docker = files.docker(fake_docker(dir.path(), "printf 'PGDMP-data'"));
        fs::create_dir_all(files.backups()).unwrap();
        for i in 0..KEEP_BACKUPS + 2 {
            fs::write(files.backups().join(format!("formunex-20000101-0000{i:02}.dump")), "old").unwrap();
        }
        let b = backup(&files, &docker, "pre upgrade!").unwrap();
        assert!(b.name.ends_with("-preupgrade.dump"), "{}", b.name);
        assert_eq!(fs::read(&b.path).unwrap(), b"PGDMP-data");
        let left = files.list_backups();
        assert_eq!(left.len(), KEEP_BACKUPS);
        assert_eq!(left[0].name, b.name);
    }

    #[cfg(unix)]
    #[test]
    fn create_admin_passes_password_by_environment_only() {
        let dir = tempfile::tempdir().unwrap();
        let log = dir.path().join("args.txt");
        let script =
            format!("echo \"$*\" > {}; echo \"$FORMUNEX_NEW_USER_PASSWORD\" >> {}", log.display(), log.display());
        let files = StackFiles::new(dir.path());
        let docker = files.docker(fake_docker(dir.path(), &script));
        create_admin(&docker, "admin", "管理员", "s3cret-pw").unwrap();
        let text = fs::read_to_string(&log).unwrap();
        let mut lines = text.lines();
        let args = lines.next().unwrap();
        assert!(args.contains("exec -T -e FORMUNEX_NEW_USER_PASSWORD api python scripts/create_user.py admin"));
        assert!(!args.contains("s3cret-pw"));
        assert_eq!(lines.next(), Some("s3cret-pw"));
        assert!(create_admin(&docker, "bad name;", "x", "pw").is_err());
    }
}
