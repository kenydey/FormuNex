// Regenerate src/api/openapi.json + src/api/schema.d.ts from the FastAPI app (方案 §3.1: types come from
// OpenAPI, never by hand). Needs the backend virtualenv: ../backend/.venv (or PYTHON=/path/to/python).
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

// P3-E3: resolve the repo from this file, not the caller's cwd —
// `npm run gen:api` from anywhere else used to write into the wrong tree.
const here = dirname(fileURLToPath(import.meta.url));
const root = dirname(here); // frontend/
const backend = join(root, "..", "backend"); // repo backend, not frontend/backend

const python = process.env.PYTHON || join(backend, ".venv/bin/python");
const json = execFileSync(python, ["-c", "import json; from app.main import app; print(json.dumps(app.openapi()))"], {
  cwd: backend,
  env: { ...process.env, FORMUNEX_DB_URL: process.env.FORMUNEX_DB_URL || "sqlite:///:memory:" },
  maxBuffer: 64 * 1024 * 1024,
}).toString();
const spec = JSON.parse(json);
writeFileSync(join(root, "src/api/openapi.json"), JSON.stringify(spec, null, 1) + "\n");
const ast = await openapiTS(spec);
writeFileSync(join(root, "src/api/schema.d.ts"), "/* Generated by scripts/gen-api.mjs — do not edit. */\n" + astToString(ast));
console.log(`openapi: ${Object.keys(spec.paths).length} paths`);
